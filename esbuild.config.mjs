import esbuild from 'esbuild';
import process from 'process';
import { builtinModules } from 'node:module';

import { readFileSync } from 'node:fs';

// kenat is MIT-licensed and bundled into main.js, so its notice must ship with it.
const kenatLicense = readFileSync('node_modules/kenat/LICENSE', 'utf8').trim();

const banner = `/*
THIS IS A GENERATED/BUNDLED FILE BY ESBUILD
if you want to view the source, please visit the github repository of this plugin

Ethiopian Calendar for Obsidian
Copyright (c) 2026 ashenafidl
Released under the MIT License.

This file bundles third-party code under its own license:

kenat (https://github.com/MelakuDemeke/kenat)
${kenatLicense}
*/
`;

const prod = process.argv[2] === 'production';

const context = await esbuild.context({
	banner: {
		js: banner,
	},
	entryPoints: ['src/main.ts'],
	bundle: true,
	external: [
		'obsidian',
		'electron',
		'@codemirror/autocomplete',
		'@codemirror/collab',
		'@codemirror/commands',
		'@codemirror/language',
		'@codemirror/lint',
		'@codemirror/search',
		'@codemirror/state',
		'@codemirror/view',
		'@lezer/common',
		'@lezer/highlight',
		'@lezer/lr',
		...builtinModules,
	],
	format: 'cjs',
	target: 'es2021',
	logLevel: 'info',
	sourcemap: prod ? false : 'inline',
	treeShaking: true,
	outfile: 'main.js',
	minify: prod,
});

if (prod) {
	await context.rebuild();
	process.exit(0);
} else {
	await context.watch();
}
